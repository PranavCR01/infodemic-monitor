"""Report writer for compare_blind.py. Notes on each disagreement are written
by the model pass after reading both rows and their evidence; they are
observations for the adjudicator, not decisions."""
from collections import Counter
import judge
from compare_blind_notes import NOTES

HEADER = ("> **Model-model agreement between two Claude labelling passes. Not human "
          "inter-annotator agreement; errors may be correlated.**\n")

def esc(s):
    return (s or "").replace("|", "\\|").replace("\n", " ")

def ev(r):
    s, c = r.get("evidence_supporting", ""), r.get("evidence_contradicting", "")
    out = []
    if s: out.append("S: " + s)
    if c: out.append("C: " + c)
    return esc("; ".join(out)) or "—"

def confusion(pairs, cats):
    cats = [c for c in cats if any(c in p for p in pairs)]
    cnt = Counter(pairs)
    head = "| first \\ model | " + " | ".join(cats) + " |\n|---|" + "---|" * len(cats) + "\n"
    rows = "".join("| %s | %s |\n" % (a, " | ".join(str(cnt[(a, b)]) or "0" for b in cats)) for a in cats)
    return head + rows

def note(key):
    return esc(NOTES.get(key, "(no note)"))

def write(fv, mv, fc, mc, pairs, uf, um, kappa, path):
    L = ["# Blind relabel comparison (blind_model_pass_v1 vs first pass)\n\n", HEADER, "\n"]
    vids = sorted({r["video_id"] for r in mv}, key=lambda v: int(v[1:]))
    L.append("41 blind-sample videos (REVIEW.md). First pass: `claims.csv` / `videos.csv` "
             "(`labelling_pipeline_v1`). Second pass: `blind/model_relabel_*.csv` "
             "(`blind_model_pass_v1`), labelled from transcripts and live PubMed only, "
             "committed before the main CSVs were opened (see `blind/READ_LOG.md`). "
             "Generated by `scripts/compare_blind.py`.\n")
    # claim extraction
    L.append("\n## 1. Claim extraction\n\n")
    L.append("| | first pass | model pass |\n|---|---|---|\n| claims | %d | %d |\n| matched | %d | %d |\n| unmatched | %d | %d |\n"
             % (len(fc), len(mc), len(pairs), len(pairs), len(uf), len(um)))
    L.append("\nMatched share: %.0f%% of first-pass claims, %.0f%% of model-pass claims.\n"
             % (100 * len(pairs) / len(fc), 100 * len(pairs) / len(mc)) + "\n")
    L.append("**Matching rule.** Within a video, one-to-one. Similarity is the overlap "
             "coefficient of content words (lower-cased, accents stripped, 3+ letters, "
             "stop words removed). A pair is a candidate when the two time windows overlap "
             "(each widened by 3 s) and similarity ≥ 0.34, or similarity ≥ 0.6 at any time; "
             "candidates are taken greedily, best first. %d pairs were then matched by hand "
             "on meaning (listed in `MANUAL_MATCH` with reasons), e.g. the same claim phrased "
             "as a negation in the other pass. A compound claim in one pass matches at most "
             "one of the split claims in the other; the rest show up as unmatched.\n"
             % sum(1 for p in pairs if p[3].startswith("manual")))
    # stance / verdict
    st = [(f["speaker_stance"], m["speaker_stance"]) for f, m, *_ in pairs]
    vd = [(f["claim_verdict"], m["claim_verdict"]) for f, m, *_ in pairs]
    po_s, k_s = kappa(st); po_v, k_v = kappa(vd)
    L.append("\n## 2. Agreement on the %d matched claims\n\n" % len(pairs))
    L.append("| field | agreement | Cohen's kappa |\n|---|---|---|\n| speaker_stance | %.1f%% (%d/%d) | %.2f |\n| claim_verdict | %.1f%% (%d/%d) | %.2f |\n"
             % (100 * po_s, sum(a == b for a, b in st), len(st), k_s,
                100 * po_v, sum(a == b for a, b in vd), len(vd), k_v))
    L.append("\n**speaker_stance** (rows first pass, columns model pass)\n\n" + confusion(st, judge.STANCES))
    L.append("\n**claim_verdict**\n\n" + confusion(vd, judge.VERDICTS))
    # video level
    fvd = {r["video_id"]: r for r in fv}; mvd = {r["video_id"]: r for r in mv}
    lab = [(fvd[v]["video_level_label"], mvd[v]["video_level_label"]) for v in vids]
    bas = [(fvd[v]["misinfo_basis"] or "(none)", mvd[v]["misinfo_basis"] or "(none)") for v in vids]
    lb = [(fvd[v]["video_level_label"] + ("/" + fvd[v]["misinfo_basis"] if fvd[v]["misinfo_basis"] else ""),
           mvd[v]["video_level_label"] + ("/" + mvd[v]["misinfo_basis"] if mvd[v]["misinfo_basis"] else "")) for v in vids]
    oos = [("out_of_scope" in fvd[v]["case_tags"].split(";"), "out_of_scope" in mvd[v]["case_tags"].split(";")) for v in vids]
    insc = [v for v in vids if not ("out_of_scope" in fvd[v]["case_tags"].split(";") and "out_of_scope" in mvd[v]["case_tags"].split(";"))]
    lab_in = [(fvd[v]["video_level_label"], mvd[v]["video_level_label"]) for v in insc]
    L.append("\n## 3. Video level (%d videos)\n\n" % len(vids))
    rows = [("video_level_label", lab), ("misinfo_basis (empty = none)", bas),
            ("label + basis combined", lb), ("video_level_label, excluding videos both passes tagged out_of_scope (n=%d)" % len(insc), lab_in),
            ("out_of_scope tag", oos)]
    L.append("| field | agreement | Cohen's kappa |\n|---|---|---|\n")
    for name, p in rows:
        po, k = kappa(p)
        L.append("| %s | %.1f%% (%d/%d) | %.2f |\n" % (name, 100 * po, sum(a == b for a, b in p), len(p), k))
    L.append("\n**label + basis** (rows first pass, columns model pass)\n\n" +
             confusion(lb, sorted({x for p in lb for x in p})))
    # disagreement tables
    L.append("\n## 4. Every disagreement\n\n")
    L.append("Notes say which side looks right and why, as an input to adjudication. "
             "Nothing here changes `claims.csv` or `videos.csv`; the project lead decides.\n\n**Systematic causes seen.** (1) Model-pass misses on v114 and v122: its transcript viewer truncated long caption lines and printed only the first caption lines, so later on-screen claims were never seen. (2) Granularity: one pass splits a sentence that the other keeps whole, and most unmatched claims are this. (3) The UNSUPPORTED/INSUFFICIENT boundary when evidence exists for an ingredient or a related intervention (v113, v149) and when a claim is detox (v120); the model applied it inconsistently. (4) Both stance disagreements are polarity artefacts (one pass stores the negation of the other's claim), so stance agrees fully in substance.\n")
    L.append("\n### 4a. Video label or basis differs\n\n| video | first pass | model pass | note |\n|---|---|---|---|\n")
    n_v = 0
    for v in vids:
        a, b = fvd[v], mvd[v]
        if (a["video_level_label"], a["misinfo_basis"]) != (b["video_level_label"], b["misinfo_basis"]):
            n_v += 1
            L.append("| %s | %s %s | %s %s | %s |\n" % (v, a["video_level_label"], a["misinfo_basis"],
                     b["video_level_label"], b["misinfo_basis"], note((v, "video"))))
    L.append("\n### 4b. Matched claims whose stance or verdict differs\n\n"
             "| video | first-pass claim | model claim | stance (first → model) | verdict (first → model) | first-pass evidence | model evidence | note |\n|---|---|---|---|---|---|---|---|\n")
    n_c = 0
    for f, m, s, how in pairs:
        if f["speaker_stance"] != m["speaker_stance"] or f["claim_verdict"] != m["claim_verdict"]:
            n_c += 1
            L.append("| %s | %s: %s | %s: %s | %s → %s | %s → %s | %s | %s | %s |\n" % (
                f["video_id"], f["claim_id"], esc(f["claim_text"]), m["claim_id"], esc(m["claim_text"]),
                f["speaker_stance"], m["speaker_stance"], f["claim_verdict"], m["claim_verdict"],
                ev(f), ev(m), note((f["video_id"], f["claim_id"], m["claim_id"]))))
    L.append("\n### 4c. Claims only one pass extracted\n\n| video | pass | claim | stance | verdict | evidence | note |\n|---|---|---|---|---|---|---|\n")
    for who, rows_ in (("first", uf), ("model", um)):
        for r in rows_:
            L.append("| %s | %s | %s: %s | %s | %s | %s | %s |\n" % (r["video_id"], who, r["claim_id"], esc(r["claim_text"]),
                     r["speaker_stance"], r["claim_verdict"], ev(r), note((r["video_id"], who, r["claim_id"]))))
    L.append("\n### 4d. Matched pairs (for checking the matcher)\n\n| video | first | model | similarity | how |\n|---|---|---|---|---|\n")
    for f, m, s, how in pairs:
        L.append("| %s | %s | %s | %.2f | %s |\n" % (f["video_id"], f["claim_id"], m["claim_id"], s, esc(how)))
    summary = "\n## Summary\n\n- To adjudicate: **%d** video-level disagreements, **%d** matched-claim disagreements (stance or verdict), **%d** claims extracted by only one pass (%d first, %d model).\n" % (n_v, n_c, len(uf) + len(um), len(uf), len(um))
    L.insert(4, summary)
    open(path, "w", encoding="utf-8").write("".join(L))
    print("wrote", path, "| video disagreements", n_v, "| claim disagreements", n_c, "| unmatched", len(uf), len(um))
    return n_v, n_c
